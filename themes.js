function HS_getTheme(themeId) {
  return HS_THEMES[themeId] || HS_THEMES["default"];
}

function HS_resolveActiveTheme(themeMode, customTheme) {
  if (themeMode === "customized" && customTheme && HS_THEMES[customTheme]) {
    return HS_THEMES[customTheme];
  }
  return HS_THEMES["default"];
}

function HS_applyThemeVariables(targetElement, theme) {
  if (!targetElement || !theme || !theme.vars) return;
  for (const [prop, val] of Object.entries(theme.vars)) {
    targetElement.style.setProperty(prop, val);
  }
  if (theme.vars["--color-scheme"]) {
    targetElement.style.colorScheme = theme.vars["--color-scheme"];
  }
}

